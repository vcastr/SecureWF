-- Run this entire file in Supabase SQL Editor.
-- It stores email addresses in a protected table and exposes only safe leaderboard fields.

create table if not exists public.word_find_leaderboard (
  id bigint generated by default as identity primary key,
  display_name text not null check (char_length(trim(display_name)) between 1 and 40),
  email text not null check (
    char_length(email) between 5 and 120
    and email = lower(email)
    and email ~* '^[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}$'
  ),
  score integer not null check (score = 10),
  duration_seconds integer not null check (duration_seconds between 1 and 86400),
  completed_at timestamptz not null default now()
);

alter table public.word_find_leaderboard enable row level security;

-- Remove all direct public access first. The game receives insert-only access below.
revoke all on table public.word_find_leaderboard from public, anon, authenticated;
revoke all on sequence public.word_find_leaderboard_id_seq from public, authenticated;
grant usage, select on sequence public.word_find_leaderboard_id_seq to anon;
grant insert (display_name, email, score, duration_seconds)
  on public.word_find_leaderboard to anon;

-- The public game can submit a completed result, but cannot select, update or delete rows.
drop policy if exists "allow completed game inserts" on public.word_find_leaderboard;
create policy "allow completed game inserts"
on public.word_find_leaderboard
for insert
to anon
with check (
  score = 10
  and duration_seconds between 1 and 86400
  and char_length(trim(display_name)) between 1 and 40
  and char_length(email) between 5 and 120
  and email = lower(email)
  and email ~* '^[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}$'
);

-- Safe public leaderboard function. It deliberately does not return email, id or timestamp.
create or replace function public.get_word_find_leaderboard()
returns table (display_name text, score integer, duration_seconds integer)
language sql
stable
security definer
set search_path = public
as $$
  select l.display_name, l.score, l.duration_seconds
  from public.word_find_leaderboard as l
  order by l.score desc, l.duration_seconds asc, l.completed_at asc
  limit 10;
$$;

revoke all on function public.get_word_find_leaderboard() from public, authenticated;
grant execute on function public.get_word_find_leaderboard() to anon;

create index if not exists word_find_rank_idx
  on public.word_find_leaderboard (score desc, duration_seconds asc, completed_at asc);
